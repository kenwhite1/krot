// Все локации одним списком (для набора «Всё»).
const ALL: Location[] = [...CLASSIC, ...TRAVEL, ...SPECIAL]

// Список локаций активного набора. Именно по нему крот гадает, и его же видят
// все игроки как подсказку для вопросов.
export function locationsForPack(pack: PackId): Location[] {
  switch (pack) {
    case 'classic': return CLASSIC
    case 'travel': return TRAVEL
    case 'special': return SPECIAL
    case 'all': return ALL
  }
}

export interface PackInfo {
  id: PackId
  name: string
  emoji: string
  blurb: string
  count: number
}

export const PACK_INFO: PackInfo[] = [
  ...PACKS.map(p => ({ id: p.id as PackId, name: p.name, emoji: p.emoji, blurb: p.blurb, count: p.locations.length })),
  { id: 'all', name: 'Всё', emoji: '🎲', blurb: 'Все локации сразу', count: ALL.length },
]

export function packName(pack: PackId): string {
  return PACK_INFO.find(p => p.id === pack)?.name ?? 'Классика'
}
