const clamp01 = (n: number) => Math.max(0, Math.min(1, n))

// Ответ бота на заданный вопрос: текст и tell (0..1, насколько «не в тему»).
// Город отвечает чисто; крот тем глаже, чем выше сложность (мастер врёт убедительно).
export function answerForBot(s: GameState, answerer: EnginePlayer, rng: Rng): { text: string; tell: number } {
  if (!answerer.isMole) {
    // даже честный житель порой мнётся: распределения города и крота пересекаются,
    // поэтому подозрение шумит и стол не вычисляет крота как часы.
    return { text: pick(TOWN_ANSWERS, rng), tell: clamp01(0.1 + rng.next() * 0.24) }
  }
  const smoothChance = s.difficulty === 'hard' ? 0.82 : s.difficulty === 'normal' ? 0.62 : 0.42
  if (rng.next() < smoothChance) {
    return { text: pick(MOLE_SMOOTH, rng), tell: clamp01(0.2 + rng.next() * 0.18) }
  }
  return { text: pick(MOLE_SHAKY, rng), tell: clamp01(0.48 + rng.next() * 0.2) }
}

export interface AnswerOption {
  text: string
  tell: number
  vibe: 'solid' | 'easy' | 'risky'
}

// Варианты ответа для живого игрока, когда его спрашивают. Город знает локацию и
// может ответить чисто; крот не знает места и блефует. Чем «глаже» выбор, тем
// меньше tell, тем меньше на нём виснет подозрение.
export function humanAnswerOptions(isMole: boolean, rng: Rng): AnswerOption[] {
  if (!isMole) {
    return [
      { text: pick(TOWN_ANSWERS, rng), tell: clamp01(0.08 + rng.next() * 0.12), vibe: 'solid' },
      { text: 'Да нормально, по-свойски тут.', tell: clamp01(0.2 + rng.next() * 0.12), vibe: 'easy' },
      { text: 'Ха, а это секрет, не скажу.', tell: clamp01(0.55 + rng.next() * 0.2), vibe: 'risky' },
    ]
  }
  return [
    { text: pick(MOLE_SMOOTH, rng), tell: clamp01(0.22 + rng.next() * 0.12), vibe: 'solid' },
    { text: 'Да как и все, ничего необычного.', tell: clamp01(0.4 + rng.next() * 0.12), vibe: 'easy' },
    { text: pick(MOLE_SHAKY, rng), tell: clamp01(0.6 + rng.next() * 0.18), vibe: 'risky' },
  ]
}

