// ============================================================================
// Голос стола. На допросе игроки задают друг другу короткие вопросы и отвечают.
// Город отвечает уверенно и по делу (они знают локацию), крот юлит и уходит от
// прямого ответа (он не знает, где все оказались). Текст реплик берётся отсюда;
// насколько ответ «не в тему» (tell) кормит модель подозрения в движке.
//
// Импорт типов из движка только типовой (стирается при сборке): рантайм-цикла нет.
// ============================================================================

import type { GameState, EnginePlayer } from './engine'
