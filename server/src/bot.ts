import { Bot, webhookCallback } from 'grammy'
import { BOT_TOKEN } from './auth'
import { APP_URL } from './env'

export const bot = BOT_TOKEN ? new Bot(BOT_TOKEN) : null

const OPEN = 'Играть 🕵️'

export function appKeyboard(startParam?: string) {
  if (!APP_URL) return undefined
  const url = startParam ? `${APP_URL}?startapp=${encodeURIComponent(startParam)}` : APP_URL
  return { inline_keyboard: [[{ text: OPEN, web_app: { url } }]] }
}

if (bot) {
  void bot.api.setMyDescription(
    '«Крот» это игра про скрытую личность в компании. Все за столом знают одну общую ' +
      'локацию, и у каждого там своя роль. Все, кроме одного. Этот один крот: он не знает, ' +
      'где оказался, и должен прикинуться своим.\n\n' +
      'По очереди вы задаёте друг другу короткие вопросы и отвечаете. Город ищет крота по ' +
      'неуверенным ответам, а крот вслушивается и пытается угадать локацию. В конце ' +
      'голосуете: поймали крота, победил город; ошиблись, выигрывает крот.\n\n' +
      'Играй с ботами трёх уровней, заходи в быструю игру онлайн или зови друзей в комнату ' +
      'по коду. Заходи, у нас тут весело и подозрительно!',
  ).catch(() => {})
  void bot.api.setMyShortDescription(
    'Крот: найди своего среди чужих. Лови крота по неуверенным ответам или сам уходи от облавы. С ботами или друзьями 🕵️',
  ).catch(() => {})

  void bot.api.setMyCommands([
    { command: 'start', description: 'Открыть игру' },
    { command: 'play', description: 'Сыграть партию' },
    { command: 'rules', description: 'Как играть' },
    { command: 'about', description: 'Об игре' },
    { command: 'help', description: 'Помощь' },
  ]).catch(() => {})

  bot.command('start', async ctx => {
    const payload = ctx.match?.toString() ?? ''
    const startParam = payload.startsWith('room_') ? payload : undefined
    const name = ctx.from?.first_name || 'друг'
    await ctx.reply(
      `Привет, ${name}! Это «Крот» 🕵️\n\n` +
        'Если совсем просто: вся компания знает одну общую локацию, скажем, пляж или ' +
        'больница, и у каждого там своя роль. Все, кроме одного. Этот один крот: он не ' +
        'знает, где все оказались, и старается не выдать себя.\n\n' +
        'По очереди вы спрашиваете друг друга: часто ли тут бываешь, чем пахнет, во что ' +
        'одет. Город отвечает уверенно и по делу, а крот юлит, ведь места он не знает. ' +
        'Заметил, кто плавает в ответах? Зови на голосование.\n\n' +
        'Поймаете крота, побеждает город. Выгоните своего, смеётся крот. А ещё крот может ' +
        'в любой момент назвать локацию: угадал, забрал победу себе.\n\n' +
        'Можно сыграть с ботами на трёх уровнях, найти случайный стол онлайн или собрать ' +
        'друзей в комнату по коду. Жми «Играть» внизу и присаживайся к столу. Стол уже ' +
        'заждался 🕵️',
      { reply_markup: appKeyboard(startParam) },
    )
  })

  bot.command('play', async ctx => {
    await ctx.reply('Накрываю на стол 🕵️ Заходи в игру!', { reply_markup: appKeyboard() })
  })

  bot.command('rules', async ctx => {
    await ctx.reply(
      'Правила «Крота» 🕵️\n\n' +
        'Цель: городу вычислить крота, кроту уцелеть и угадать локацию.\n\n' +
        '• В начале партии все, кроме одного, видят общую локацию и свою роль на ней. Один ' +
        'игрок крот: локации он не знает.\n' +
        '• По кругу игроки задают друг другу по одному короткому вопросу и отвечают. Вопросы ' +
        'любые, лишь бы выманить чужака.\n' +
        '• Город отвечает так, чтобы показать: я тут свой, но вслух локацию не называет, ' +
        'иначе крот её услышит.\n' +
        '• Крот вслушивается, подыгрывает и пытается понять, где все собрались.\n' +
        '• Любой может созвать голосование. Выбрали крота, побеждает город. Выгнали ' +
        'невиновного или стол не договорился, побеждает крот.\n' +
        '• Крот может вместо этого назвать локацию. Угадал, победа крота. Промахнулся, ' +
        'победа города.\n\n' +
        'Список возможных локаций виден всем: по нему удобно задавать вопросы, и по нему же ' +
        'крот гадает.',
      { reply_markup: appKeyboard() },
    )
  })

  bot.command('about', async ctx => {
    await ctx.reply(
      '«Крот» 🕵️\n\n' +
        'Своя игра про скрытую личность в компании, без заимствований: коротко, весело и ' +
        'подозрительно. Из простых вопросов вырастает целый детектив за столом.\n\n' +
        'Как можно играть:\n' +
        '• Одиночная игра против ботов, три уровня сложности.\n' +
        '• Быстрая игра, случайный стол онлайн прямо сейчас.\n' +
        '• С друзьями, общая комната по коду из четырёх символов.\n\n' +
        'Партия короткая, а характеров хватает на вечер. Заходи разок, потом не ' +
        'оторвёшься 💛',
      { reply_markup: appKeyboard() },
    )
  })

  bot.command('help', async ctx => {
    await ctx.reply(
      '«Крот» 🕵️, игра про поиск чужого среди своих.\n\n' +
        'Команды:\n' +
        '/start - открыть игру\n' +
        '/play - сыграть партию\n' +
        '/rules - как играть\n' +
        '/about - об игре\n' +
        '/help - это сообщение\n\n' +
        'Жми кнопку ниже, чтобы играть 👇',
      { reply_markup: appKeyboard() },
    )
  })
}

export const botWebhook = bot ? webhookCallback(bot, 'hono') : null
